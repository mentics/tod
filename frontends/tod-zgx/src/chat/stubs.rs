//! stops the page's effect that made it. So each is registered: a call nothing
//! waits on (`ui.invoke`) does nothing; one that returns a promise (`ui.call`)
//! rejects, saying what it is, and the page shows that as its own failure.
//! (Generated from the page's `ui.invoke("...")` / `ui.call("...")` names; a new
//! page call shows up as the error above, and goes in a list here, or gets a
//! real answer in chat.rs.)

