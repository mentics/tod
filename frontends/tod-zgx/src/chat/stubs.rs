pub fn install(host: &ScriptHost) {
    for name in NO_ANSWER {
        host.action(*name, move |_| {});
    }
    for name in REJECTED {
        host.async_action(*name, move |_| async move {
            Err(format!("{name} is unavailable in this chat panel"))
        });
    }
}
